/**
 * Writes the KTX2 transcoder worker that the kids world loads.
 *
 * three's KTX2Loader normally assembles this worker in the page and hands it
 * to `new Worker()` as a blob: URL. A blob worker inherits the document's
 * Content-Security-Policy, and the transcoder is emscripten output whose
 * embind layer builds its call wrappers with `new Function(...)` — so under
 * our policy, which deliberately withholds 'unsafe-eval', the worker throws
 * before it finishes starting and every Basis texture load hangs unresolved.
 *
 * A worker loaded from a real same-origin URL gets its OWN policy from that
 * response's headers instead of inheriting the page's. Serving the same code
 * from a file therefore lets the one context that needs `new Function` have
 * it, while the document — where an injection would actually be worth
 * something — keeps a policy with no eval in it at all. See
 * packages/server/lib/app/headers.ts for the paired response header.
 *
 * The body is assembled from three's own KTX2Loader rather than copied, so a
 * three upgrade cannot leave a stale worker behind: re-run this script and the
 * file matches the installed version. Run it after `npm install` bumps three.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { KTX2Loader } from "three/examples/jsm/loaders/KTX2Loader.js";

const dir = join(import.meta.dirname, "..", "root", "public", "kids-assets", "basis");
const fn = KTX2Loader.BasisWorker.toString();

const body = [
  "/* GENERATED by scripts/build-ktx2-worker.mjs — do not edit. */",
  "/* Mirrors the blob worker three's KTX2Loader builds in-page, served from",
  "   a URL so it carries its own CSP. Regenerate after upgrading three. */",
  "/* constants */",
  "let _EngineFormat = " + JSON.stringify(KTX2Loader.EngineFormat),
  "let _EngineType = " + JSON.stringify(KTX2Loader.EngineType),
  "let _TranscoderFormat = " + JSON.stringify(KTX2Loader.TranscoderFormat),
  "let _BasisFormat = " + JSON.stringify(KTX2Loader.BasisFormat),
  "/* basis_transcoder.js */",
  readFileSync(join(dir, "basis_transcoder.js"), "utf8"),
  "/* worker */",
  fn.substring(fn.indexOf("{") + 1, fn.lastIndexOf("}")),
].join("\n");

const out = join(dir, "ktx2-worker.js");
writeFileSync(out, body);
console.log(`wrote ${out} (${(body.length / 1024).toFixed(0)} KiB)`);
