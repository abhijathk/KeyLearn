#!/usr/bin/env node
/**
 * Writes a world's title sign into the kids bundle as an inline image.
 *
 *   node scripts/kids-world-sign.mjs village|hero|dino sign.png
 *
 * The input is a transparent render of the sign, trimmed to its edges (the
 * three shipped were rendered from the Meshy GLBs in Blender, 640 across at
 * most). It is encoded to WebP and written as a data URI into
 * page-kids/lib/world-signs/<world>.ts, which the loading card draws small
 * over the runner and Time Keepers' picker draws first in its header.
 *
 * INLINE, NOT FETCHED, because the point of it is to be on screen the moment
 * the loading card is — before any request has had a chance to queue behind
 * the world's models. And not under kids-assets/: `warmWorld` pre-downloads
 * every file there for the child's world, used or not.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const NAMES = {
  village: "Time Keepers",
  hero: "Hero Trials",
  dino: "Dino Run",
};
const [, , world, src] = process.argv;
if (!(world in NAMES) || src == null) {
  console.error(
    "usage: node scripts/kids-world-sign.mjs village|hero|dino sign.png",
  );
  process.exit(1);
}
const REPO = new URL("..", import.meta.url).pathname;
const tmp = join(mkdtempSync(join(tmpdir(), "kids-sign-")), "sign.webp");
execFileSync("cwebp", [
  "-quiet",
  "-q",
  "75",
  "-m",
  "6",
  "-alpha_q",
  "100",
  src,
  "-o",
  tmp,
]);
const b64 = readFileSync(tmp).toString("base64");
const out = join(REPO, `packages/page-kids/lib/world-signs/${world}.ts`);
writeFileSync(
  out,
  `/** GENERATED by scripts/kids-world-sign.mjs — do not edit. The ${NAMES[world]} title sign. */
export const SIGN =
  "data:image/webp;base64,${b64}";
`,
);
console.log(
  `kids-world-sign: ${world} ${Math.round((b64.length * 3) / 4 / 1024)} KB`,
);
