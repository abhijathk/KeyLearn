#!/usr/bin/env node
/**
 * Content-addresses everything under `kids-assets/`, into one manifest.
 *
 *   node scripts/kids-manifest.mjs [--check]
 *
 * WHY THIS EXISTS. These files are fetched by paths with no version in them,
 * so the server cannot promise a browser that `Peeli.glb` will never change —
 * and `cachecontrol.ts` says as much in as many words: "immutable would be a
 * lie, and a re-exported model would never reach a returning learner". The
 * cache is therefore capped at a day, and every later visit spends 180-odd
 * conditional requests before the first model can be decoded.
 *
 * A hash in the URL makes the promise true. Different bytes are a different
 * URL, so `immutable` stops being a lie, a changed model reaches everybody on
 * their next load, and a local copy can be kept for a year instead of a day.
 *
 * NOTHING IS RENAMED ON DISK. The hash goes in a path SEGMENT — 
 * `/kids-assets/v1a2b3c4d/models/…` — which the server strips before it looks
 * for the file (see `static-cache.ts`). One file, many URLs, no build output
 * to keep in step with the source and no duplicated megabytes.
 *
 * GROUPS ARE THE OTHER HALF. Each entry carries the world it belongs to, so a
 * child playing Dino Run is never asked to fetch a banyan tree. Derived from
 * the path, because that is how this tree is already organised.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const REPO = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const ROOT = join(REPO, "root/public/kids-assets");
const OUT = join(ROOT, "manifest.json");

/**
 * Which world each directory belongs to.
 *
 * `shared` is the floor every world pays: the Basis transcoder, the sky maps
 * and the ground textures. `village` is far and away the heaviest — it is the
 * one with a village in it — which is exactly why this split is worth having.
 */
const GROUP_OF = (rel) => {
  const top = rel.split("/")[0];
  const second = rel.split("/")[1] ?? "";
  if (top === "models") {
    if (second === "dino") return "dino";
    if (second === "hero" || second === "abee") return "hero";
    if (second.startsWith("village") || second === "ak-3d-pack" ||
        second === "kuttichathan" || second === "nature") return "village";
    return "shared";
  }
  if (top === "faces" || top === "cards") return "village";
  return "shared";
};

const walk = (dir) => {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      out.push(...walk(full));
    } else if (full !== OUT) {
      out.push(full);
    }
  }
  return out;
};

const files = walk(ROOT).sort();
const assets = {};
let bytes = 0;
for (const full of files) {
  const rel = relative(ROOT, full).split(sep).join("/");
  const buf = readFileSync(full);
  // Eight hex characters. The whole tree is under two hundred files, so the
  // odds of a collision are nil and a shorter segment keeps the URLs readable
  // in a network panel, which is where anybody debugging this will be.
  const hash = createHash("sha256").update(buf).digest("hex").slice(0, 8);
  assets[rel] = { u: `v${hash}/${rel}`, b: buf.length, g: GROUP_OF(rel) };
  bytes += buf.length;
}

// The manifest's OWN version, so the service worker can tell one build of the
// whole tree from another without diffing every entry.
const version = createHash("sha256")
  .update(JSON.stringify(assets))
  .digest("hex")
  .slice(0, 12);

const manifest = { version, assets };
const json = JSON.stringify(manifest);

if (process.argv.includes("--check")) {
  let current = null;
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // Never written.
  }
  if (current !== json) {
    console.error(
      `kids-manifest: out of date — run "node scripts/kids-manifest.mjs"`,
    );
    process.exit(1);
  }
  console.log(`kids-manifest: up to date (${files.length} files)`);
} else {
  writeFileSync(OUT, json);
  /*
   * AND THE SAME MAP AS A MODULE THE PAGE IMPORTS.
   *
   * Fetching the manifest at runtime looked tidier and cost fourteen seconds
   * on a cold load: it went out at module init, queued behind the browser's
   * six connections to the same host — every one of them busy with a model —
   * and arrived long after the URLs it was supposed to rewrite had already
   * been requested the old way.
   *
   * Bundled, it is there before the first request, there is no round trip to
   * lose a race against, and webpack's own content hash covers it. The JSON
   * is still written because the service worker reads it without the page.
   */
  writeFileSync(
    join(REPO, "packages/page-kids/lib/asset-manifest.ts"),
    `// GENERATED by scripts/kids-manifest.mjs — do not edit.\n` +
      `//\n` +
      `// Every file under kids-assets, and the content-hashed URL it is also\n` +
      `// reachable at. See the script for why, and \`versioned()\` in world.ts\n` +
      `// for where it is spent.\n` +
      `export const ASSET_VERSION = ${JSON.stringify(version)};\n` +
      `export const ASSET_MAP: Readonly<\n` +
      `  Record<string, { readonly u: string; readonly b: number; readonly g: string }>\n` +
      `> = ${JSON.stringify(assets, null, 2)};\n`,
  );
  const byGroup = {};
  for (const a of Object.values(assets)) {
    byGroup[a.g] = (byGroup[a.g] ?? 0) + a.b;
  }
  console.log(`kids-manifest ${version}  ${files.length} files  ${(bytes / 1048576).toFixed(1)} MB`);
  for (const [g, b] of Object.entries(byGroup).sort((x, y) => y[1] - x[1])) {
    console.log(`  ${g.padEnd(8)} ${(b / 1048576).toFixed(1)} MB`);
  }
}
